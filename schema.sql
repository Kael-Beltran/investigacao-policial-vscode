CREATE TABLE IF NOT EXISTS casos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo TEXT,
    tipo_crime TEXT,
    descricao TEXT
);

CREATE TABLE IF NOT EXISTS investigadores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT,
    cargo TEXT,
    email TEXT
);

CREATE TABLE IF NOT EXISTS caso_investigadores (
    caso_id BIGINT NOT NULL REFERENCES casos(id) ON DELETE CASCADE,
    investigador_id BIGINT NOT NULL REFERENCES investigadores(id) ON DELETE CASCADE,
    PRIMARY KEY (caso_id, investigador_id)
);

CREATE INDEX IF NOT EXISTS idx_caso_investigadores_investigador_id
    ON caso_investigadores (investigador_id);

CREATE TABLE IF NOT EXISTS suspeitos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT,
    cpf TEXT,
    data_nascimento DATE,
    endereco TEXT,
    caso_id BIGINT REFERENCES casos(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS evidencias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao TEXT,
    tipo TEXT,
    local_encontrada TEXT,
    data_coleta DATE,
    caso_id BIGINT REFERENCES casos(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS testemunhas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT,
    telefone TEXT,
    endereco TEXT,
    depoimento TEXT,
    caso_id BIGINT REFERENCES casos(id) ON DELETE SET NULL
);
